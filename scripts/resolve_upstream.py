"""Maintainer-only: resolve Windows wheels from official PyPI in a clean uv env."""
import hashlib
import json
import os
import subprocess
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "runtime"
TMP = ROOT / "tmp" / "upstream-resolve"
UV_URL = "https://github.com/astral-sh/uv/releases/download/0.13.4/uv-x86_64-pc-windows-msvc.zip"
UV_SHA = "ccec7508a07d9933d7cb1261880633efcf1f30d6e6eddab21823f1dae6f23225"


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "zotero-codex-build/0.2"}), timeout=120) as r:
        return r.read()


def main():
    OUT.mkdir(exist_ok=True)
    TMP.mkdir(parents=True, exist_ok=True)
    archive = TMP / "uv.zip"
    if not archive.exists() or hashlib.sha256(archive.read_bytes()).hexdigest() != UV_SHA:
        data = fetch(UV_URL)
        assert hashlib.sha256(data).hexdigest() == UV_SHA
        archive.write_bytes(data)
    with zipfile.ZipFile(archive) as z:
        (TMP / "uv.exe").write_bytes(z.read("uv.exe"))
    env = {k: v for k, v in os.environ.items() if not k.upper().startswith(("UV_", "PIP_", "PYTHON"))}
    env.update(UV_CACHE_DIR=str(TMP / "cache"), UV_PYTHON_INSTALL_DIR=str(TMP / "python"), UV_NO_PROGRESS="1")
    source = OUT / "requirements.in"
    source.write_text("BabelDOC==0.6.4\nbitstring>=4.3,<5\npeewee>=3.17.8,<4\npymupdf>=1.26.7,<2\nopencv-python-headless>=4.10,<5\n", encoding="utf-8")
    subprocess.run([str(TMP / "uv.exe"), "--no-config", "pip", "compile", str(source), "--python-version", "3.12.15", "--python-platform", "x86_64-pc-windows-msvc", "--only-binary", ":all:", "--index-url", "https://pypi.org/simple", "--generate-hashes", "--no-emit-index-url", "-o", str(TMP / "resolved.txt")], check=True, env=env, stdout=subprocess.DEVNULL)
    # Select one exact Windows/CPython wheel per resolved package. Publish only
    # that file's digest and immutable files.pythonhosted.org URL in the lock.
    import re
    from packaging.tags import cpython_tags, compatible_tags
    from packaging.utils import parse_wheel_filename
    tags = list(cpython_tags((3, 12), platforms=["win_amd64"])) + list(compatible_tags((3, 12), interpreter="cp312", platforms=["win_amd64"]))
    rank = {t: i for i, t in reversed(list(enumerate(tags)))}
    wheels = []
    for name, version in re.findall(r"^([a-zA-Z0-9_.-]+)==([^\s\\]+)", (TMP / "resolved.txt").read_text(), re.M):
        info = json.loads(fetch(f"https://pypi.org/pypi/{name}/{version}/json"))
        choices = []
        for f in info["urls"]:
            if f["packagetype"] != "bdist_wheel" or f.get("yanked"):
                continue
            supported = parse_wheel_filename(f["filename"])[3] & rank.keys()
            if supported:
                choices.append((min(rank[t] for t in supported), f))
        if not choices:
            raise RuntimeError(f"No compatible wheel: {name} {version}")
        f = min(choices, key=lambda pair: pair[0])[1]
        wheels.append(dict(name=name, version=version, filename=f["filename"], url=f["url"], sha256=f["digests"]["sha256"], size=f["size"], license=info["info"].get("license_expression") or info["info"].get("license"), projectURLs=info["info"].get("project_urls")))
        print(name, version, flush=True)
    (OUT / "wheels-windows-x64.json").write_text(json.dumps(wheels, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (OUT / "requirements-windows-x64.lock").write_text("# CPython 3.12 Windows x64; official PyPI; generated by scripts/resolve_upstream.py\n" + "".join(f"{w['url']} --hash=sha256:{w['sha256']}\n" for w in wheels), encoding="utf-8")
    catalog = json.loads(fetch("https://raw.githubusercontent.com/astral-sh/uv/0.13.4/crates/uv-python-managed/download-metadata.json"))
    catalog = {k: v for k, v in catalog.items() if v.get("sha256") == "7a2aef48e5ee569e310b29b32681debbc5d888e92790d85331a47736c6b06aad"}
    assert len(catalog) == 1, "Pinned Python not present in uv catalog"
    (OUT / "python-downloads.json").write_text(json.dumps(catalog, indent=2) + "\n", encoding="utf-8")
    print("Wheels:", len(wheels), "bytes:", sum(w["size"] for w in wheels))


if __name__ == "__main__":
    main()
